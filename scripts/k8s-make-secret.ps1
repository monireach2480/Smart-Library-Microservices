<#
.SYNOPSIS
    Generates k8s/02-secret.yaml from your cloud PostgreSQL details.

.DESCRIPTION
    Prompts for the managed-database host, user and password, generates the three application secrets,
    and writes k8s/02-secret.yaml. That file is git-ignored - never commit it.

    Create the six databases first:  deploy/cloud-db/init-cloud-databases.sql

.EXAMPLE
    .\scripts\k8s-make-secret.ps1
    .\scripts\k8s-make-secret.ps1 -DbHost "ep-cool-rain-12345.ap-southeast-1.aws.neon.tech" -DbUser "library"
#>
[CmdletBinding()]
param(
    [string]$DbHost,
    [string]$DbUser = "library",
    [string]$SslMode = "require"
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$outFile = Join-Path $root "k8s\02-secret.yaml"

function New-RandomSecret([int]$Length = 48) {
    $chars = (48..57) + (65..90) + (97..122)
    -join ($chars | Get-Random -Count $Length | ForEach-Object { [char]$_ })
}

if (-not $DbHost) {
    $DbHost = Read-Host "Cloud PostgreSQL host (e.g. ep-xxxx.aws.neon.tech)"
}
if (-not $DbHost) { throw "A database host is required." }

$securePw = Read-Host "Password for user '$DbUser'" -AsSecureString
$dbPass = [System.Net.NetworkCredential]::new("", $securePw).Password
if (-not $dbPass) { throw "A database password is required." }

# URL-encode the characters that would break a connection string
$encPass = [uri]::EscapeDataString($dbPass)
$encUser = [uri]::EscapeDataString($DbUser)

function New-DbUrl([string]$Database) {
    "postgresql+psycopg2://${encUser}:${encPass}@${DbHost}/${Database}?sslmode=$SslMode"
}

$secretKey = New-RandomSecret 48
$internalKey = New-RandomSecret 32
$adminKey = New-RandomSecret 24

$yaml = @"
# GENERATED by scripts/k8s-make-secret.ps1 on $(Get-Date -Format "yyyy-MM-dd HH:mm").
# Contains live credentials - git-ignored. Do not commit, do not paste into a report.
apiVersion: v1
kind: Secret
metadata:
  name: smart-library-secrets
  namespace: smart-library
  labels:
    app.kubernetes.io/part-of: smart-library
type: Opaque
stringData:
  SECRET_KEY: "$secretKey"
  INTERNAL_API_KEY: "$internalKey"
  ADMIN_REGISTRATION_KEY: "$adminKey"

  AUTH_DATABASE_URL: "$(New-DbUrl 'auth_db')"
  CATALOG_DATABASE_URL: "$(New-DbUrl 'catalog_db')"
  INVENTORY_DATABASE_URL: "$(New-DbUrl 'inventory_db')"
  BORROWING_DATABASE_URL: "$(New-DbUrl 'borrowing_db')"
  FINE_DATABASE_URL: "$(New-DbUrl 'fine_db')"
  REVIEW_DATABASE_URL: "$(New-DbUrl 'review_db')"
"@

Set-Content -Path $outFile -Value $yaml -Encoding UTF8

Write-Host "`nWrote $outFile" -ForegroundColor Green
Write-Host "  database host   : $DbHost"
Write-Host "  databases       : auth_db, catalog_db, inventory_db, borrowing_db, fine_db, review_db"
Write-Host "  ADMIN_REGISTRATION_KEY = $adminKey" -ForegroundColor Yellow
Write-Host "    (you need this to create the first ADMIN account)"
Write-Host "`nNext:  .\scripts\k8s-deploy.ps1" -ForegroundColor Green
